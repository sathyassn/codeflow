func testPolicy() *EnforcementPolicy {
	return &EnforcementPolicy{
		ProtectedBranches: []string{"main", "master", "release/*", "production"},
		SensitiveFilePatterns: []string{
			`\.env$`, `\.env\.`, `credentials`, `\.pem$`, `\.key$`,
			`id_rsa`, `id_ed25519`, `\.secret`, `password`,
		},
		GitFormat: GitFormat{
			CommitTypes: []string{
				"feat", "fix", "bugfix", "hotfix", "docs", "refactor",
				"test", "chore", "style", "perf", "build", "ci",
				"revert", "merge", "plan", "refine",
			},
			BranchTypes: []string{
				"feature", "feat", "fix", "bugfix", "hotfix", "release",
				"docs", "refactor", "test", "chore",
			},
			BranchPrefixes: []string{
				"feat/", "fix/", "docs/", "refactor/", "test/", "chore/",
			},
			AIAttributionPatterns: []string{
				"Claude", "Anthropic", "ChatGPT", "Co-Authored-By: Claude",
			},
			Subject: SubjectConfig{
				MaxLength:            50,
				RequireLowercaseType: true,
				ForbidTrailingPeriod: true,
			},
			Body: BodyConfig{
				Format:        "bullets_only",
				MaxBullets:    3,
				LineMaxLength: 72,
			},
		},
	}
}

func TestValidateCommitMsg_ValidMessages(t *testing.T) {
	t.Parallel()

	policy := testPolicy()
	tests := []struct {
		name string
		msg  string
	}{
		{"simple feat", "feat: add user login"},
		{"docs type", "docs: update README"},
		{"chore type", "chore: update dependencies"},
		{"with bullet body", "feat: add feature\n\n- first change\n- second change"},
		{"single bullet", "fix: resolve bug\n\n- fixed the issue"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if err := ValidateCommitMsg(tt.msg, policy); err != nil {
				t.Errorf("expected valid but got error: %v", err)
			}
		})
	}
}

