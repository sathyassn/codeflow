// containsErrorString checks if err's Error() contains substr, handling
// CommitMsgErrors which collect multiple messages.
func containsErrorString(err error, substr string) bool {
	if err == nil {
		return false
	}
	// Check the full Error() string.
	if strings.Contains(err.Error(), substr) {
		return true
	}
	// Check individual errors in CommitMsgErrors.
	if cmErrs, ok := err.(*CommitMsgErrors); ok {
		for _, e := range cmErrs.Errors {
			if strings.Contains(e, substr) {
				return true
			}
		}
	}
	return false
}
