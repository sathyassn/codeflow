//! Operator feedback items (issue 75): one item, one file at
//! `project-management/feedback/FB-NNN.md`, its id issued by the shared
//! registry like any other record (`ids::Kind::Fb`).
//!
//! An item keeps the operator's words verbatim and the agent's reading apart
//! from them, and moves by one transition table:
//!
//! ```text
//!   received --placed --in--> placed --closed --evidence--> closed
//!       |                        |                             |
//!       +-- declined --confirmed-by operator --reason ---------+-> (terminal)
//!       +-- superseded --by FB-NNN (also from placed or closed)
//! ```
//!
//! `codeflow validate --docs` checks every item's structure ([`lint`]); the
//! index (`INDEX.md`) is generated on demand by `codeflow feedback list
//! --write`, and a present index that no longer matches the items is a
//! warning, never a failure. Topics come from `[feedback] topics` in
//! `.codeflow/project.toml` ([`crate::scaffold::state::FeedbackConfig`]).

