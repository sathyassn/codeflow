/* Produces direction E's payload, exactly the way an agent would have to.
 *
 * The `media` block takes a bounded base64 image and nothing else, so the agent
 * must render its figure out of band, at one width, in one mode, and paste the
 * bytes into the document. This script does that: it opens direction B's page,
 * screenshots the first figure at the wide viewport in light mode, and writes
 * the data URI into directions/e-raster/payload.js.
 *
 * Everything direction E loses is a consequence of this step, not of a design
 * choice made later.
 */
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';

const ROOT = path.resolve(import.meta.dirname, '..');
const REPO = path.resolve(ROOT, '..', '..', '..');
const WEB = path.join(REPO, 'crates/codeflow-present/web/node_modules');
const MIME = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript' };

const server = http.createServer((req, res) => {
  const file = path.resolve(ROOT, decodeURIComponent(req.url.split('?')[0]).replace(/^\/+/, ''));
  if (!file.startsWith(ROOT) || !fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
  res.writeHead(200, { 'content-type': MIME[path.extname(file)] ?? 'application/octet-stream' });
  res.end(fs.readFileSync(file));
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const port = server.address().port;

const { chromium } = await import(path.join(WEB, 'playwright-core/index.mjs'));
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'light', deviceScaleFactor: 2 });
await page.goto(`http://127.0.0.1:${port}/directions/b-scene/index.html`, { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
const shot = await page.locator('#fig-plan').screenshot();
await browser.close();
server.close();

const base64 = shot.toString('base64');
fs.writeFileSync(
  path.join(ROOT, 'directions/e-raster/payload.js'),
  `/* Generated by tools/build-raster.mjs. This is the whole of what a media block\n` +
  ` * can carry: ${shot.length} bytes of PNG, rendered once at 1440px in light mode at\n` +
  ` * 2x, with no structure, no tokens, no mode and no text the page can reflow. */\n` +
  `window.w4raster = {\n` +
  `  bytes: ${shot.length},\n` +
  `  renderedAt: { width: 1440, mode: 'light', scale: 2 },\n` +
  `  dataUri: 'data:image/png;base64,${base64}',\n` +
  `};\n`,
);
console.log(`raster payload: ${shot.length} bytes -> ${Math.round((base64.length / 1024))} KiB base64`);
